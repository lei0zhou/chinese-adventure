// Build a simple land-only map of China and its region (no political borders) with city pins.
// Source: world-atlas land-50m (Natural Earth, public domain). Usage: NODE_PATH=... node tools/build_map.mjs
import fs from 'fs'; import path from 'path'; import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const d3 = require('d3-geo'); const topo = require('topojson-client');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const land = require('world-atlas/land-50m.json');
const W = 1000, H = 760;
const proj = d3.geoConicConformal().parallels([25, 47]).rotate([-105, 0]).center([0, 36])
  ;
const pts = []; for (let lon = 88; lon <= 129; lon += 1) { pts.push([lon, 20.5], [lon, 47.5]); } for (let lat = 20.5; lat <= 47.5; lat += 1) { pts.push([88, lat], [129, lat]); }
const bbox = { type: 'MultiPoint', coordinates: pts };
proj.fitExtent([[0, 0], [W, H]], bbox).clipExtent([[0, 0], [W, H]]);
const pathGen = d3.geoPath(proj).digits(1);
const geo = topo.feature(land, land.objects.land);
const d = pathGen(geo);
const src = fs.readFileSync(path.join(root, 'data/content.js'), 'utf8');
const C = JSON.parse(src.slice(src.indexOf('=') + 1).trim().replace(/;$/, ''));
const cities = {};
for (const u of C.units) { const [x, y] = proj([u.city.lon, u.city.lat]); cities[u.id] = [Math.round(x), Math.round(y)]; }
fs.writeFileSync(path.join(root, 'data/map.js'),
  '/* Land outline from Natural Earth via world-atlas (public domain). Generated by tools/build_map.mjs. */\n' +
  'window.MAPDATA=' + JSON.stringify({ w: W, h: H, land: d, cities }) + ';\n');
console.log('path chars', d.length, cities);
