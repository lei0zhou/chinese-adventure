// Bundle hanzi-writer stroke data for every character in the vocabulary into data/strokes.js.
// Usage: NODE_PATH=<dir with node_modules> node tools/build_strokes.mjs
// Needs: npm i hanzi-writer-data@2.0.1   (Arphic Public License; see vendor/hanzi-writer-data.ARPHICPL.TXT)
import fs from 'fs'; import path from 'path'; import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = fs.readFileSync(path.join(root, 'data/content.js'), 'utf8');
const C = JSON.parse(src.slice(src.indexOf('=') + 1).trim().replace(/;$/, ''));
const chars = [...new Set(C.words.map(w => w.hz).join('').split(''))];
const dataDir = path.dirname(require.resolve('hanzi-writer-data/package.json'));
const out = {}; const missing = [];
for (const ch of chars) {
  const f = path.join(dataDir, ch + '.json');
  if (!fs.existsSync(f)) { missing.push(ch); continue; }
  const d = JSON.parse(fs.readFileSync(f, 'utf8'));
  out[ch] = { strokes: d.strokes, medians: d.medians, radStrokes: d.radStrokes };
}
fs.writeFileSync(path.join(root, 'data/strokes.js'),
  '/* Stroke data from hanzi-writer-data 2.0.1 (Make Me a Hanzi; Arphic Public License, see vendor/hanzi-writer-data.ARPHICPL.TXT). Generated by tools/build_strokes.mjs. */\n' +
  'window.STROKES=' + JSON.stringify(out) + ';\n');
console.log('chars', chars.length, 'bundled', Object.keys(out).length, 'missing', missing.join(''));
